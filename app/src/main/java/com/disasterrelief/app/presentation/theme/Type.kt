/**
 * Typography system using Google Fonts' Inter family.
 * Inter is chosen for its excellent readability at small sizes and
 * clean geometric design, ideal for data-dense emergency dashboards.
 */

private val googleFontProvider = GoogleFont.Provider(
    providerAuthority = "com.google.android.gms.fonts",
    providerPackage = "com.google.android.gms",
    certificates = emptyList() // Uses system-installed GMS fonts
)

